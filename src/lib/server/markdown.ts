import { marked } from 'marked';
import sanitizeHtml from 'sanitize-html';

export interface TocEntry {
	id: string;
	text: string;
	level: number;
}

const SANITIZE_OPTIONS = {
	allowedTags: [
		'h2',
		'h3',
		'h4',
		'p',
		'em',
		'strong',
		'a',
		'ul',
		'ol',
		'li',
		'blockquote',
		'code',
		'pre',
		'hr',
		'img'
	],
	allowedAttributes: {
		a: ['href', 'title', 'rel'],
		img: ['src', 'alt', 'title']
	},
	transformTags: {
		a: sanitizeHtml.simpleTransform('a', { rel: 'noopener noreferrer' })
	},
	allowedSchemes: ['https']
};

function slugify(text: string): string {
	return (
		text
			.toLowerCase()
			.replace(/[^a-z0-9\s-]/g, '')
			.trim()
			.replace(/\s+/g, '-')
			.slice(0, 60) || 'section'
	);
}

/**
 * Renders admin-supplied Markdown to sanitized HTML (PRD §5.4, §6.6).
 * The input is treated as untrusted: only a strict subset of tags survives
 * sanitization, and only https URLs are allowed. Heading ids are injected
 * after sanitization, generated by us from a restricted charset, so articles
 * can carry a table of contents.
 */
export function renderMarkdown(source: string): {
	html: string;
	toc: TocEntry[];
	readingMinutes: number;
} {
	const raw = marked.parse(source, { async: false }) as string;
	const sanitized = sanitizeHtml(raw, SANITIZE_OPTIONS);

	const toc: TocEntry[] = [];
	const used = new Map<string, number>();

	const html = sanitized.replace(
		/<h([234])>([\s\S]*?)<\/h\1>/g,
		(_match: string, depth: string, inner: string) => {
			const plain = inner.replace(/<[^>]*>/g, '').trim();
			let id = slugify(plain);
			const seen = used.get(id) ?? 0;
			used.set(id, seen + 1);
			if (seen > 0) id = `${id}-${seen + 1}`;
			toc.push({ id, text: plain, level: Number(depth) });
			return `<h${depth} id="${id}">${inner}</h${depth}>`;
		}
	);

	// Reading time is computed from the actual content (PRD §4.2 Journey C).
	const words = source
		.trim()
		.split(/\s+/)
		.filter(Boolean).length;

	return {
		html,
		toc: toc.filter((entry) => entry.level <= 3),
		readingMinutes: Math.max(1, Math.round(words / 220))
	};
}
