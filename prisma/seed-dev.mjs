// [DEV] fixture seeder (PRD §3.3, §5.3). Inserts clearly labeled placeholder
// content for development, screenshots, and automated tests only.
//   - Refuses to run when NODE_ENV=production.
//   - Every title/excerpt carries an explicit [DEV] label.
//   - Idempotent: upserts by slug, so re-running never duplicates.
// Production content must be entered by the administrator through the CMS.
import { existsSync, readFileSync } from 'node:fs';
import { PrismaClient } from '@prisma/client';
import { PrismaBetterSqlite3 } from '@prisma/adapter-better-sqlite3';

if (process.env.NODE_ENV === 'production') {
	console.error('Refusing to seed [DEV] placeholder fixtures with NODE_ENV=production.');
	process.exit(1);
}

if (existsSync('.env')) {
	for (const line of readFileSync('.env', 'utf8').split('\n')) {
		const match = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)\s*$/);
		if (match && !(match[1] in process.env)) {
			process.env[match[1]] = match[2].replace(/^["']|["']$/g, '');
		}
	}
}

const url = process.env.DATABASE_URL;
if (!url) {
	console.error('DATABASE_URL is not set. Copy .env.example to .env first.');
	process.exit(1);
}

const prisma = new PrismaClient({ adapter: new PrismaBetterSqlite3({ url }) });

const now = new Date();

const articleBody = [
	'This is a **development placeholder**. It exists so editors, layouts, and tests can be exercised before any real content is approved. It must not be published to production.',
	'',
	'## Structure and typography',
	'',
	'Articles render with a reading-optimized serif, generous line height, and a deliberate measure. Headings create the table of contents automatically.',
	'',
	'## Formatting that survives sanitization',
	'',
	'- **Bold** and *italic* text',
	'- [Links to real sources](https://www.svelte.dev) open with `rel="noopener"`',
	'- Inline `code` is supported',
	'',
	'> A blockquote demonstrates restrained brass emphasis.',
	'',
	'## Media and navigation',
	'',
	'Related content appears only when real relationships exist. The table of contents anchors to the ids generated by the sanitizer.',
	'',
	'### A third-level heading',
	'',
	'Final paragraph of the placeholder.'
].join('\n');

try {
	await prisma.article.upsert({
		where: { slug: 'dev-example-insight' },
		create: {
			title: '[DEV] Example insight — placeholder',
			slug: 'dev-example-insight',
			excerpt: '[DEV] Placeholder article for development. Replace with real, verified content before any production publish.',
			body: articleBody,
			status: 'published',
			publishedAt: now,
			category: 'Development',
			tags: JSON.stringify(['dev'])
		},
		update: {}
	});

	await prisma.article.upsert({
		where: { slug: 'dev-draft-insight' },
		create: {
			title: '[DEV] Draft insight — never publicly visible',
			slug: 'dev-draft-insight',
			excerpt: '[DEV] Draft placeholder used to verify drafts stay private.',
			body: 'This draft must never appear on public pages or in search results.',
			status: 'draft',
			category: 'Development',
			tags: JSON.stringify(['dev'])
		},
		update: {}
	});

	// Big Buck Bunny (Blender Foundation, Creative Commons) is a real, freely
	// embeddable public video used only as a labeled development fixture.
	await prisma.video.upsert({
		where: { slug: 'dev-fixture-video' },
		create: {
			title: '[DEV] Fixture video — Big Buck Bunny',
			slug: 'dev-fixture-video',
			description: '[DEV] Placeholder video for development. Embeds the open-source film Big Buck Bunny (CC BY 3.0, Blender Foundation).',
			provider: 'youtube',
			providerVideoId: 'aqz-KE-bpKQ',
			status: 'published',
			featured: true,
			publishedAt: now,
			category: 'Development',
			tags: JSON.stringify(['dev'])
		},
		update: {}
	});

	await prisma.video.upsert({
		where: { slug: 'dev-draft-video' },
		create: {
			title: '[DEV] Draft video — never publicly visible',
			slug: 'dev-draft-video',
			description: '[DEV] Draft placeholder used to verify drafts stay private.',
			provider: 'youtube',
			providerVideoId: 'aqz-KE-bpKQ',
			status: 'draft',
			tags: JSON.stringify(['dev'])
		},
		update: {}
	});

	await prisma.audioEpisode.upsert({
		where: { slug: 'dev-fixture-episode' },
		create: {
			title: '[DEV] Fixture episode — 30 second tone',
			slug: 'dev-fixture-episode',
			description: '[DEV] Placeholder audio: a 30-second generated tone, clearly labeled as a development fixture — not a real episode.',
			audioSourceUrl: '/fixtures/dev-tone-30s.wav',
			durationSeconds: 30,
			status: 'published',
			publishedAt: now,
			category: 'Development',
			tags: JSON.stringify(['dev'])
		},
		update: {}
	});

	await prisma.audioEpisode.upsert({
		where: { slug: 'dev-draft-episode' },
		create: {
			title: '[DEV] Draft episode — never publicly visible',
			slug: 'dev-draft-episode',
			description: '[DEV] Draft placeholder used to verify drafts stay private.',
			audioSourceUrl: '/fixtures/dev-tone-30s.wav',
			status: 'draft',
			tags: JSON.stringify(['dev'])
		},
		update: {}
	});

	console.log('[DEV] fixtures seeded (idempotent upserts):');
	console.log('  published: article dev-example-insight, video dev-fixture-video, episode dev-fixture-episode');
	console.log('  drafts:     article dev-draft-insight, video dev-draft-video, episode dev-draft-episode');
	console.log('All fixture content is [DEV]-labeled. Replace it with verified content in production.');
} finally {
	await prisma.$disconnect();
}
